const _enKeySet = Object.keys(PACKS.en).sort().join("\0");
for (const loc of WISHLIST_UI_LOCALES) {
  const keys = Object.keys(PACKS[loc]);
  if (keys.length !== Object.keys(PACKS.en).length || keys.sort().join("\0") !== _enKeySet) {
    throw new Error(`Wishlist UI pack key mismatch for locale: ${loc}`);
  }
}

function normalizeWishlistLocale(locale: string | undefined | null): WishlistLocale {
  const raw = String(locale || "en")
    .trim()
    .toLowerCase()
    .replace("_", "-");
  if (raw === "pt-pt" || raw.startsWith("pt-")) return "pt";
  const code = raw.split("-")[0] as WishlistLocale;
  return PACKS[code] ? code : "en";
}

/** Lookup UI string. EN fallback is for crashes / unknown locales only. */
export function wishlistT(
  locale: string | WishlistLocale,
  key: string,
  vars?: Record<string, string>,
): string {
  const loc = normalizeWishlistLocale(locale);
  let text = PACKS[loc]?.[key] || PACKS.en[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, v);
    }
  }
  return text;
}

export function wishlistOwnerStats(
  locale: string | WishlistLocale,
  wishes: number,
  shares: number,
  views: number,
): string {
  const wishPart = wishlistT(locale, wishes === 1 ? "stats.wishes.one" : "stats.wishes.other", {
    n: String(wishes),
  });
  const sharePart = wishlistT(locale, shares === 1 ? "stats.shares.one" : "stats.shares.other", {
    n: String(shares),
  });
  const viewsPart =
    views > 0
      ? ` · ${wishlistT(locale, views === 1 ? "stats.views.one" : "stats.views.other", {
          n: String(views),
        })}`
      : "";
  return `${wishPart} · ${sharePart}${viewsPart}`;
}

