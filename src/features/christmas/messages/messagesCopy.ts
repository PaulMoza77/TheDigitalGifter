/** Product UI keys that must be localized for Wave 1 (P3D coverage). */
export const REQUIRED_UI_KEYS = [
  "hero.h1",
  "hero.lede",
  "legend.recipient",
  "legend.tone",
  "cta.generate",
  "cta.generating",
  "cta.regenerate",
  "cta.copy",
  "cta.useInCard",
  "results.title",
  "empty.hint",
  "error.generate",
  "crossSell.cardCta",
] as const;

// Assert key parity: every locale pack must match EN key set.
const _enKeySet = Object.keys(PACKS.en).sort().join("\0");
for (const loc of MESSAGES_UI_LOCALES) {
  const keys = Object.keys(PACKS[loc]);
  if (keys.length !== Object.keys(PACKS.en).length || keys.sort().join("\0") !== _enKeySet) {
    throw new Error(`Messages UI pack key mismatch for locale: ${loc}`);
  }
}

export function messagesT(
  key: string,
  locale: MessagesLocale = "en",
  vars?: Record<string, string>,
): string {
  let text = PACKS[locale]?.[key] || PACKS.en[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, v);
    }
  }
  return text;
}
